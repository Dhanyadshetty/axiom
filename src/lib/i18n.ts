export function normalizeLanguage(value?: string | null): Language {
  return value === "de" ? "de" : "en";
}

export function getGreeting(language: Language, date = new Date()) {
  const hour = date.getHours();
  if (hour < 12) return language === "de" ? "Guten Morgen" : "Good morning";
  if (hour < 18) return language === "de" ? "Guten Nachmittag" : "Good afternoon";
  return language === "de" ? "Guten Abend" : "Good evening";
}

export function formatDateTime(language: Language, date = new Date()) {
  const locale = language === "de" ? "de-DE" : "en-US";
  return new Intl.DateTimeFormat(locale, {
    weekday: "long",
    year: "numeric",
    month: "long",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  }).format(date);
}

export function t<K extends Namespace>(language: Language, section: K) {
  return copy[language][section] as Record<string, string>;
}

export function tx(language: Language, namespace: Namespace, key: string): string {
  return copy[language][namespace][key] ?? copy.en[namespace][key] ?? key;
}

export async function getActiveLanguage(): Promise<Language> {
  try {
    const { cookies } = await import("next/headers");
    const store = await cookies();
    return normalizeLanguage(store.get(LANGUAGE_COOKIE)?.value);
  } catch {
    return "en";
  }
}

